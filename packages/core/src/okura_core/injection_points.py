"""注入点の一覧（D17・D19・D22、SCOPE §3「注入点（ポート）」・§5.3〜5.5）：市町村・保険者ごとに変わる値の **形** と、
注入されていないときの **候補**。値そのもの（条例の率・額、級地、保険者の運用）はここに置かない（SCOPE §4）。

候補（InjectionPoint.candidates）の決め方（D19・D21 R6）：
  - 取りうる範囲が有限で、法令で決まっているもの（級地は1級地〜3級地、料か税か、軽減の割合の3通り）は、その全部。
  - 保険者の運用は、調査（docs の kenpo・kyosai）で集めた運用の型に限る（D21 R6「保険者データがないときは調査で集めた運用の型に限る」）。
    型の名前には、その型を示した保険者・組合の資料の略称（docs の出典一覧の名前）を書く。
  - 均等割の非課税の額は、政令の基準どおりに条例が定めた場合の級地ごとの額（docs で集めた条例の例〔札幌市・柏市〕はどれもこの型）。
  - 率・額のように範囲が有限でないもの（所得割・均等割の税率、国保の率・額・賦課限度額など）は候補を持たない。
    データがなければ、その値に依存する値は未確定（決める手段＝注入）になる。既定値（標準税率など）で計算しない。

出典は docs/public-sources の節（取得日・URL・版はそこにある）。法令の値（所得割の非課税の 35万円・10万円・32万円、森林環境税の
1,000円、国保の政令の賦課限度額など）は注入点ではなく、規則モジュールのパラメータに置く（README「注入しないもの」）。
"""

