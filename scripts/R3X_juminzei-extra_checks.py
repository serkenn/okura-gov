def notice_text(name):
    """PDF から取り出した行をつなぐ（頁の区切りと頁番号の行を除く）。頁ごとの開始位置も返す。"""
    lines = (PDFT / f"{name}_lines.txt").read_text(encoding="utf-8").splitlines()
    buf, starts, page = [], [], 0
    for ln in lines:
        m = re.match(r"=== page (\d+) ===", ln)
        if m:
            page = int(m.group(1))
            starts.append((len("".join(buf)), page))
            continue
        if ln.startswith("# file=") or re.fullmatch(r"-\d+-", ln.strip()):
            continue
        buf.append(norm(ln))
    return "".join(buf), starts


def page_at(starts, pos):
    p = None
    for off, pg in starts:
        if off <= pos:
            p = pg
    return p


