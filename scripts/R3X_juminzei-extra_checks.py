def housing_credit(nendo, shitei, kyojyunen, tokutei, credit_it, tax_before, taxable_it, basic_ded_it, shi_wari, ken_wari, version=None):
    """住宅借入金等特別税額控除（地方税法附則第5条の4。旧：附則第5条の4の2）。
    nendo: 令和の年度（8 or 9）。kyojyunen: 西暦の居住年。tokutei: 特定取得・特別特定取得（居住年 2014〜2021）か。
    credit_it: 前年分の所得税の住宅借入金等特別税額控除額（第5項第1号。外部で計算した値）
    tax_before: 前年分の所得税の額（第5項第2号。住宅借入金等特別控除などを適用しない額）
    taxable_it: 前年分の所得税の課税総所得金額・課税退職所得金額・課税山林所得金額の合計額
    basic_ded_it: 前年分の所得税の基礎控除の額（措法第41条の16の2第1項の適用後）
    shi_wari / ken_wari: 第314条の3・第314条の6（第35条・第37条）を適用した後の市町村民税・道府県民税の所得割の額
    返す値：段ごとの値（Fraction）。所得割を超える部分の扱い（打ち切り）は H として示す。"""
    version = version or choose_version(nendo, kyojyunen)
    steps = {"版": version}
    ranges = {"old": [(1999, 2006), (2009, 2025)], "r8": [(2009, 2025)], "r9": [(2009, 2030)]}[version]
    if not any(lo <= kyojyunen <= hi for lo, hi in ranges):
        steps.update({"対象": False, "理由": f"居住年 {kyojyunen} は版 {version} の範囲 {ranges} の外"})
        return steps
    add = max(0, basic_ded_it - 480000) if (version != "old" and 2016 <= kyojyunen <= 2025) else 0
    base = taxable_it + add
    diff = max(0, credit_it - tax_before)
    if tokutei and 2014 <= kyojyunen <= 2021:
        r_shi, r_ken = (F(56, 1000), F(14, 1000)) if shitei else (F(42, 1000), F(28, 1000))
        c_shi, c_ken = (109200, 27300) if shitei else (81900, 54600)
    else:
        r_shi, r_ken = (F(4, 100), F(1, 100)) if shitei else (F(3, 100), F(2, 100))
        c_shi, c_ken = (78000, 19500) if shitei else (58500, 39000)
    s_shi, s_ken = (F(4, 5), F(1, 5)) if shitei else (F(3, 5), F(2, 5))
    steps.update({"対象": True, "加算（基礎控除−48万円）": add, "控除限度額の基": base, "①−②": diff})
    total = F(0)
    for nm, share, rate, cap, wari in (("市町村民税", s_shi, r_shi, c_shi, shi_wari), ("道府県民税", s_ken, r_ken, c_ken, ken_wari)):
        kojo = diff * share
        lim = min(base * rate, F(cap))
        amt = min(kojo, lim)
        total += amt
        steps[nm] = {"按分": share, "控除額（限度前）": kojo, "率": rate, "上限": cap, "控除限度額": lim, "控除額": amt,
                     "所得割（控除前）": wari, "所得割から引ける額（H：所得割を超えない）": min(amt, F(wari))}
    steps["控除額の合計"] = total
    return steps


def dividend_credit(haito, kabu, shi_wari, ken_wari):
    """配当割額・株式等譲渡所得割額の控除（第314条の9・第37条の4）。shi_wari/ken_wari は控除の基になる所得割の額。"""
    tot = F(haito + kabu)
    shi, ken = tot * F(3, 5), tot * F(2, 5)
    shi_used, ken_used = min(shi, F(shi_wari)), min(ken, F(ken_wari))
    return {"配当割額＋株式等譲渡所得割額": tot, "市町村民税から控除すべき額（3/5）": shi, "道府県民税から控除すべき額（2/5）": ken,
            "市町村民税で控除した額": shi_used, "道府県民税で控除した額": ken_used,
            "控除不足額（第314条の9第2項・第3項）": (shi - shi_used) + (ken - ken_used)}


def fmt(v):
    if isinstance(v, F):
        return str(v.numerator) if v.denominator == 1 else f"{v.numerator}/{v.denominator}（={float(v):.4f}）"
    if isinstance(v, dict):
        return "{" + ", ".join(f"{k}: {fmt(x)}" for k, x in v.items()) + "}"
    return str(v)


