def months(start, end):
    """暦に従った月数（1月未満は1月）。判定コアとは別に、日付を1月ずつ進めて数える。"""
    n = 0
    cur = start
    while cur <= end:
        n += 1
        y, m = cur.year + (cur.month // 12), cur.month % 12 + 1
        day = min(start.day, [31, 29 if y % 4 == 0 and (y % 100 or y % 400 == 0) else 28, 31, 30, 31, 30, 31, 31, 30, 31, 30, 31][m - 1])
        cur = dt.date(y, m, day)
    return n


def examples():
    out = {}
    # 生産高比例法（新）：取得価額 1,000,000、採掘予定数量 1000、採掘数量 300・500・300。累計は取得価額−1円まで
    acc, xs = 0, []
    for q in (300, 500, 300):
        a = min(math.ceil(Fraction(1_000_000 * q, 1000)), 999_999 - acc)
        acc += a
        xs.append(a)
    out["生産高比例法"] = xs
    # 旧生産高比例法：残存価額10%、95% まで、その後（取得価額−95%−1）÷5
    acc, xs = 0, []
    for q in (600, 500):
        a = min(math.ceil(Fraction(900_000 * q, 1000)), 950_000 - acc)
        acc += a
        xs.append(a)
    xs.append(math.ceil(Fraction(1_000_000 - 950_000 - 1, 5)))
    out["旧生産高比例法"] = xs
    # リース期間定額法：取得価額 1,200,000・残価保証額 200,000、リース期間 2025-04-15〜2030-04-14
    total = months(dt.date(2025, 4, 15), dt.date(2030, 4, 14))
    y25 = months(dt.date(2025, 4, 15), dt.date(2025, 12, 31))
    out["リース期間の月数"] = [total, y25]
    out["リース期間定額法"] = [math.ceil(Fraction(1_000_000 * y25, total)), math.ceil(Fraction(1_000_000 * 12, total))]
    # 経過リース期間定額法（令和8年分から）：改定取得価額 1,200,000−150,000、改定リース期間 2026-01-01〜2030-04-14
    rev = months(dt.date(2026, 1, 1), dt.date(2030, 4, 14))
    out["経過リース期間定額法"] = [rev, math.ceil(Fraction((1_200_000 - out["リース期間定額法"][0]) * 12, rev))]
    # 国外中古建物：A 損失 300・償却費 200、B 損失 50・償却費 100、国外不動産等の所得 150
    first = min(200, 300) + min(100, 50)
    second = (300 - 200)
    out["国外中古建物"] = max(0, first - max(0, 150 - second))
    return out


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    res = {"phrases": [], "web_phrases": [], "examples": examples()}
    for f, p in PHRASES:
        t = (LAWS / f).read_text(encoding="utf-8") if (LAWS / f).exists() else ""
        res["phrases"].append({"file": f, "found": p in t, "phrase": p[:60]})
    for f, p in WEB_PHRASES:
        t = (WEB / f).read_text(encoding="utf-8") if (WEB / f).exists() else ""
        res["web_phrases"].append({"file": f, "found": p in t, "phrase": p[:60]})
    sames = json.loads((LAWS / "sames.json").read_text(encoding="utf-8"))
    res["changed_between_versions"] = {k: v["changed_between_consecutive"] for k, v in sames.items()}
    (OUT / "result.json").write_text(json.dumps(res, ensure_ascii=False, indent=1), encoding="utf-8")
    lines = [f"phrases found {sum(x['found'] for x in res['phrases'])}/{len(res['phrases'])}",
             f"web phrases found {sum(x['found'] for x in res['web_phrases'])}/{len(res['web_phrases'])}"]
    lines += [f"NOT FOUND {x['file']}: {x['phrase']}" for x in res["phrases"] + res["web_phrases"] if not x["found"]]
    lines += [f"example {k}: {v}" for k, v in res["examples"].items()]
    lines += [f"changed {k}: {v}" for k, v in res["changed_between_versions"].items()]
    (OUT / "summary.txt").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("\n".join(lines))


